#!/usr/bin/env node
// Builds design-system/BRAND-PACK.md, one readable file with everything a teammate or another
// AI tool needs about the brand:  node scripts/build-brand-pack.mjs
//
// Made from:
//   design-system/tokens.json     exact copy of the design system's project/tokens.json
//   design-system/brand-book.md   exact copy of the design system's project/README.md
//   design-system/team-notes.md   website and Google Drive notes, edited by hand here
// Never edit BRAND-PACK.md by hand; change the sources and run this again.
// scripts/check-site.mjs fails if BRAND-PACK.md is out of date.

import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const ds = join(root, 'design-system');
export const BRAND_PACK = join(ds, 'BRAND-PACK.md');
const DESIGN_SYSTEM_URL = 'https://claude.ai/artifact/GcdcUnbKB4fUmmYyLgXnSW';
const REPO_URL = 'https://github.com/emerhej/merhejtimberandtrends-site';

const cell = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const table = (head, rows) =>
  [`| ${head.join(' | ')} |`, `| ${head.map(() => '---').join(' | ')} |`, ...rows.map((r) => `| ${r.map(cell).join(' | ')} |`)].join('\n');
// Push every heading down by `by` levels so a source file fits under a section of the pack.
const demote = (md, by) => md.replace(/^(#{1,6}) /gm, (_, h) => '#'.repeat(Math.min(6, h.length + by)) + ' ');

export function buildBrandPack() {
  const t = JSON.parse(readFileSync(join(ds, 'tokens.json'), 'utf8'));
  const book = readFileSync(join(ds, 'brand-book.md'), 'utf8').trim();
  const notes = readFileSync(join(ds, 'team-notes.md'), 'utf8').trim();

  const themes = t.color.themes.map((th) => th.id);
  const themeName = Object.fromEntries(t.color.themes.map((th) => [th.id, th.name]));
  const colourValue = (v, th) => {
    if (typeof v === 'string') return v.startsWith('{') ? `same as ${v.slice(1, -1)}` : v;
    return v[th] ?? '';
  };
  const colours = table(
    ['Token', ...themes.map((th) => `${themeName[th]}${th === 'light' ? ' (brand)' : ''}`), 'Use'],
    t.color.tokens.map((c) => [`\`${c.name}\``, ...themes.map((th) => colourValue(c.value, th)), c.usage]),
  );

  const families = Object.entries(t.type.families);
  const fontName = (stack) => (stack.match(/"([^"]+)"/) || [, stack.split(',')[0]])[1];
  const fonts = table(
    ['Role', 'Font (Google Fonts)', 'Full CSS stack'],
    families.map(([role, stack]) => [role, fontName(stack), `\`${stack}\``]),
  );

  const styles = table(
    ['Style', 'Font', 'Size / line height', 'Weight', 'Use'],
    t.type.groups.flatMap((g) =>
      g.styles.map((s) => [
        `\`${s.name}\``,
        fontName(t.type.families[s.family || g.family] || g.family),
        `${s.fontSize} / ${s.lineHeight}${s.letterSpacing ? `, tracking ${s.letterSpacing}` : ''}`,
        s.fontWeight,
        s.usage,
      ]),
    ),
  );

  const scale = (group) => table(['Token', 'Value', 'Use'], (t[group]?.tokens || []).map((x) => [
    `\`${x.name}\``,
    typeof x.value === 'object' ? Object.entries(x.value).map(([k, v]) => `${themeName[k] || k}: ${v}`).join('; ') : x.value,
    x.usage,
  ]));

  return `# Merhej Timber & Trends — brand pack

Everything about the brand in one file, for teammates and for other tools (such as a ChatGPT project). The source of truth is the Merhej Timber & Trends design system in Claude (${DESIGN_SYSTEM_URL}, private to its owner); this file is a copy of it plus notes on the website and the Google Drive folder.

The master copy lives in the website repo at \`design-system/BRAND-PACK.md\` (${REPO_URL}); a copy is kept in Google Drive, in 01 Brand. It is generated by \`scripts/build-brand-pack.mjs\` from \`tokens.json\`, \`brand-book.md\` and \`team-notes.md\` in the same folder, so edit those, not this file.

Design system version ${t.version}. The logo file is \`design-system/assets/logo/merhej-logo-ivory.png\` in the repo, and in Drive under 01 Brand / Logo.

## Quick reference

### Colours

Brand materials and social posts use the Ivory theme. Forest night is only for the website's dark mode.

${colours}

### Fonts

All free on Google Fonts.

${fonts}

### Type styles

${styles}

### Spacing

${scale('spacing')}

### Corners, shadow and layout

${scale('radius')}

${scale('shadow')}

${scale('layout')}

## Brand book

${demote(book, 1)}

${demote(notes, 1)}
`;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  writeFileSync(BRAND_PACK, buildBrandPack());
  console.log('✓ wrote design-system/BRAND-PACK.md');
}
